def achievement_values(game):
    roster = getattr(game, "roster", [])
    return {
        "battle_wins": getattr(game, "battle_wins", 0),
        "highest_stage": getattr(game, "highest_stage", 0),
        "roster_count": len(roster),
        "unique_players": len({p.name for p in roster}),
        "legendary_count": sum(1 for p in roster if p.rarity == "Legendary"),
        "total_upgrades": getattr(game, "total_upgrades", 0),
        "highest_player_level": max((p.attack_level + p.block_level + p.receive_level + p.setting_level + p.serve_level for p in roster), default=0),
        "league_seasons_completed": getattr(game, "league_seasons_completed", 0),
        "league_top4_finishes": getattr(game, "league_top4_finishes", 0),
        "league_championships": getattr(game, "league_championships", 0),
        "highest_player_level_ever": getattr(game, "highest_player_level_ever", 0),
        "total_prestiges": getattr(game, "total_prestiges", 0),
    }


def achievement_progress(game, achievement):
    values = achievement_values(game)
    return min(values.get(achievement["field"], 0), achievement["target"])


def claim_achievement(game, achievement_id):
    achievement = next(
        (a for a in ACHIEVEMENTS if a["id"] == achievement_id),
        None
    )
    if achievement is None:
        return False

    claimed = set(getattr(game, "claimed_achievements", []))
    if achievement_id in claimed:
        return False

    if achievement_progress(game, achievement) < achievement["target"]:
        return False

    game.coins += achievement["coins"]
    game.gems += achievement["gems"]
    claimed.add(achievement_id)
    game.claimed_achievements = sorted(claimed)
    return True
